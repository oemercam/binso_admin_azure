import 'server-only';
import type {SessionUser} from './session';
import {withTenant} from './db';
import {authorize} from './rbac';
import {ApiError,validEmail} from './http';
import {audit} from './audit';
import {getOrganizationPlan} from './plan-access';
import {readReportExport} from './report-exports';
import {sendMail,mailLayout,mailConfigured} from './email';

type SendInput={recipient:string;subject:string;message:string;key:string};
type Delivery={id:string;recipient:string;subject:string;body:string;entity_id:string;created_by:string;status:string;created_at:string|Date};
const escape=(value:string)=>value.replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]!));
function permitted(s:SessionUser){authorize(s,'reports:read');authorize(s,'documents:write');if(s.isDemo)throw new ApiError(403,'demo_send_disabled','Versand ist für diese Testumgebung nicht verfügbar.');}
function result(row:Pick<Delivery,'id'|'status'>){return {id:row.id,status:row.status,providerAccepted:row.status==='accepted',deliveryConfirmed:false};}

/** One explicit send, no retry worker. A lost response can be checked using the
 * same key; sending/uncertain requests never trigger another provider call. */
export async function sendReport(s:SessionUser,id:string,input:SendInput){
 permitted(s);id=id.toLowerCase();
 const recipient=input.recipient.trim().toLowerCase(),subject=input.subject.trim(),message=input.message.trim();
 if(!validEmail(recipient)||recipient.length>254||/[<>,;"\r\n]/.test(recipient)||!subject||subject.length>180||/[\r\n]/.test(subject)||!message||message.length>4000||input.key.length<8||input.key.length>128)throw new ApiError(400,'invalid_report_mail','Bitte Empfänger, Betreff und Begleittext prüfen.');
 const plan=await getOrganizationPlan(s.organizationId);
 const claim=await withTenant(s.organizationId,s.userId,async c=>{
  const report=await readReportExport(c,s,id,plan);
  // Conservative application budget includes the MIME/base64 expansion; never
  // silently drop an attachment or replace it with regenerated bytes.
  if(report.pdf.length>2_000_000)throw new ApiError(413,'report_mail_too_large','Der Bericht ist für E-Mail zu gross. Bitte herunterladen oder den Zeitraum eingrenzen.');
  await c.query('select pg_advisory_xact_lock(hashtextextended($1,0))',[s.organizationId+':report-mail:'+id]);
  const key='report:'+input.key;
  const previous=(await c.query<Delivery>("select * from mail_outbox where organization_id=$1 and deduplication_key=$2 and kind='report' for update",[s.organizationId,key])).rows[0];
  if(previous){
   if(previous.entity_id!==id||previous.created_by!==s.userId||previous.recipient!==recipient||previous.subject!==subject||previous.body!==message)throw new ApiError(409,'idempotency_conflict','Die Anfragekennung wurde für andere Angaben verwendet.');
   return {existing:true,row:previous,report,company:''};
  }
  const unresolved=(await c.query("select id from mail_outbox where organization_id=$1 and kind='report' and entity_id=$2 and recipient=$3 and status in ('queued','sending','uncertain') limit 1",[s.organizationId,id,recipient])).rows[0];
  if(unresolved)throw new ApiError(409,'delivery_uncertain','Der Versand läuft oder konnte nicht sicher bestätigt werden. Bitte vor erneutem Versand prüfen.');
  const company=(await c.query('select name,legal_name from organizations where id=$1',[s.organizationId])).rows[0]??{};
  const configured=mailConfigured(),row=(await c.query<Delivery>("insert into mail_outbox(organization_id,deduplication_key,kind,entity_id,recipient,subject,body,status,attempts,last_error,created_by) values($1,$2,'report',$3,$4,$5,$6,$7,$8,$9,$10) returning *",[s.organizationId,key,id,recipient,subject,message,configured?'sending':'failed',configured?1:0,configured?null:'delivery_unavailable',s.userId])).rows[0];
  await audit(c,{organizationId:s.organizationId,userId:s.userId,action:'report.mail.requested',entityType:'report_export',entityId:id,metadata:{deliveryId:row.id,status:row.status}});
  return {existing:!configured,row,report,company:String(company.legal_name||company.name||'Binso One')};
 });
 if(claim.existing)return result(claim.row);
 let status='uncertain';
 try{
  const response=await sendMail({to:recipient,subject,text:message,html:mailLayout(subject,'<p>'+escape(message).replace(/\r?\n/g,'<br>')+'</p>',undefined,claim.report.locale,{name:claim.company}),senderName:claim.company.slice(0,160),attachments:[{name:claim.report.fileName,contentType:'application/pdf',content:claim.report.pdf}]});
  // The legacy transport field means HTTP202 accepted, never inbox delivery.
  status=response.delivered?'accepted':'failed';
 }catch{/* Ambiguous network/provider errors must never be blindly resent. */}
 return withTenant(s.organizationId,s.userId,async c=>{
  const row=(await c.query<Delivery>("update mail_outbox set status=$3,last_error=$4,updated_at=now() where organization_id=$1 and id=$2 and status='sending' returning *",[s.organizationId,claim.row.id,status,status==='accepted'?null:status==='failed'?'delivery_unavailable':'delivery_uncertain'])).rows[0];
  if(!row)throw new ApiError(409,'delivery_uncertain','Der Versand läuft oder konnte nicht sicher bestätigt werden. Bitte vor erneutem Versand prüfen.');
  await audit(c,{organizationId:s.organizationId,userId:s.userId,action:'report.mail.result',entityType:'report_export',entityId:id,metadata:{deliveryId:row.id,status}});
  return result(row);
 });
}

export async function reportDeliveries(s:SessionUser,id:string){
 permitted(s);const plan=await getOrganizationPlan(s.organizationId);
 return withTenant(s.organizationId,s.userId,async c=>{
  await readReportExport(c,s,id,plan);
  return (await c.query("select id,recipient,subject,status,created_at,updated_at from mail_outbox where organization_id=$1 and created_by=$2 and entity_id=$3 and kind='report' order by created_at desc,id desc limit 20",[s.organizationId,s.userId,id])).rows;
 },{snapshot:true});
}
