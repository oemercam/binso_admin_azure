import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
const shell = readFileSync('components/public/public-shell.tsx', 'utf8')
const menu = readFileSync('components/public/public-mobile-menu.tsx', 'utf8')
const landing = readFileSync('app/page.tsx', 'utf8')
const features = readFileSync('app/features/page.tsx', 'utf8')
const screenshots = readFileSync('components/public/marketing-screenshot.tsx', 'utf8')
const css = readFileSync('app/styles/marketing-v80.css', 'utf8')
const standardized = readFileSync('app/standardized-ui.css', 'utf8')
const responsiveTests = readFileSync('tests/e2e/responsive-robustness.spec.ts', 'utf8')

assert.equal(pkg.version, '0.80.0')
assert.match(shell, /public-site-v80/)
assert.match(shell, /v80-desktop-nav/)
assert.match(shell, /v80-footer-main/)
assert.match(menu, /v80-mobile-menu-panel/)
assert.match(menu, /aria-expanded/)
assert.match(landing, /v80-hero/)
assert.match(landing, /v80-split/)
assert.match(landing, /desktopOnly/)
assert.match(features, /v80-split/)
assert.match(features, /desktopOnly/)
assert.match(screenshots, /desktopOnly/)
assert.match(css, /grid-template-columns:auto 1fr auto/)
assert.match(css, /@media\(max-width:820px\)/)
assert.match(css, /@media\(max-width:560px\)/)
assert.match(css, /\.v80-mobile-menu-panel\[aria-hidden=\"false\"\]\{display:block\}/)
assert.match(css, /\.v80-visual \.marketing-real-screenshot img\{[^}]*object-fit:contain/)
assert.match(css, /\.v80-footer-main/)
assert.match(standardized, /marketing-v80\.css/)
assert.doesNotMatch(landing, /SwipeCarousel/)
assert.match(responsiveTests, /V80 desktop public navigation/)
assert.match(responsiveTests, /V80 mobile public navigation/)

console.log('V80 public redesign checks passed (desktop navigation, mobile menu, balanced split visuals, complete screenshots and responsive footer).')
