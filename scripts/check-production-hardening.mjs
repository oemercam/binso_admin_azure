import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(path, 'utf8')
const subscription = read('app/api/billing/subscription/route.ts')
const checkout = read('app/api/billing/checkout/route.ts')
const portal = read('app/api/billing/portal/route.ts')
const webhook = read('app/api/billing/webhook/route.ts')
const logging = read('lib/logging/server.ts')
const lifecycle = read('lib/db/repositories/subscription-lifecycle.ts')
const product = read('lib/config/product.ts')
const e2e = read('tests/e2e/self-service-hardening.spec.ts')

assert.match(subscription, /isDatabaseConfigured/)
assert.match(subscription, /service_unavailable/)
assert.match(subscription, /requestId\(request\)/)
assert.match(checkout, /enforceDistributedRateLimit/)
assert.match(portal, /enforceDistributedRateLimit/)
assert.match(product, /billingActionAttempts/)
assert.match(webhook, /billing\.webhook\.failed/)
assert.match(webhook, /Webhook-Verarbeitung fehlgeschlagen\.'/)
assert.doesNotMatch(webhook, /apiError\(500,[\s\S]*internalMessage/)
assert.match(webhook, /invoice\.paid'[\s\S]*'active'/)
assert.match(logging, /redacted-email/)
assert.match(logging, /redacted-secret/)
assert.match(logging, /timestamp/)
assert.match(lifecycle, /TRIAL_DAYS/)
assert.doesNotMatch(lifecycle, /14-day trial expired/)
assert.match(e2e, /billing API fails cleanly/)
assert.match(e2e, /30 Tage kostenlos testen/)

console.log('Production hardening check passed: billing, webhook, logging, trial and self-service acceptance guards are active.')
