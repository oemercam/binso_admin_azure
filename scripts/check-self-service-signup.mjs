import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(path, 'utf8')
const register = read('app/register/page.tsx')
const registrationApi = read('app/api/registration/route.ts')
const onboarding = read('lib/db/repositories/onboarding.ts')
const onboardingPage = read('app/onboarding/page.tsx')
const checkout = read('app/api/billing/checkout/route.ts')
const subscription = read('app/api/billing/subscription/route.ts')
const pricing = read('app/pricing/page.tsx')
const env = read('.env.example')
const migration = read('database/migrations/0016_self_service_signup.sql')
const types = read('types/domain.ts')

assert.match(types, /'trial' \| 'subscription' \| 'demo'/)
assert.match(register, /Bestätigungscode/)
assert.match(register, /query\.set\('mode', mode\)/)
assert.match(registrationApi, /body\?\.mode === 'subscription'/)
assert.match(pricing, /mode=trial/)
assert.match(pricing, /mode=subscription/)
assert.match(pricing, /mode=demo/)
assert.match(onboarding, /mode === 'subscription'/)
assert.match(onboarding, /new Date\(\)/)
assert.match(onboardingPage, /subscription-required\?source=signup/)
assert.match(checkout, /resolveMembershipContext/)
assert.match(checkout, /membership\.role !== 'owner'/)
assert.match(subscription, /resolveMembershipContext/)
assert.match(env, /AUTH_PROVIDER_NAME=external_id/)
assert.match(env, /NEXT_PUBLIC_AUTH_METHODS=email/)
assert.match(migration, /'trial','subscription','demo'/)
assert.doesNotMatch(register.toLowerCase(), /passwordhash|reset_token|password_hash/)

console.log('Self-service signup check passed: demo, trial and direct subscription are wired with External ID.')
